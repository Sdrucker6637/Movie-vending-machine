#!/usr/bin/env node
/* Regenerates fx/index.js - the map of which lazily-loaded fx pack
   (fx/cues-*.js) holds the reaction for which TMDB movie id.

   Run after adding or moving a cue:   node tools/build-fx-index.js

   Fails loudly if a TMDB id is registered in more than one pack, or if a
   cue refers to a recorded clip (fx.sfx("clip:<key>") / clips: [...])
   that has no file at fx/clips/<id>-<key>.mp3. */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const dir = path.join(__dirname, "..", "fx");
const files = fs.readdirSync(dir).filter((f) => /^cues-.+\.js$/.test(f)).sort();
const map = {};
const seen = new Map();
let clipCount = 0;

for (const file of files) {
  const name = file.replace(/\.js$/, "");
  const src = fs.readFileSync(path.join(dir, file), "utf8");
  // A pack that doesn't parse would silently never register its cues.
  new vm.Script(src, { filename: file });
  const ids = [...src.matchAll(/^ {6}id: (\d+),$/gm)].map((m) => Number(m[1]));
  for (const id of ids) {
    if (seen.has(id)) throw new Error("TMDB id " + id + " is in both " + seen.get(id) + " and " + name);
    seen.set(id, name);
  }
  map[name] = ids.sort((a, b) => a - b);

  // Every clip a cue mentions must exist for the cue's id.
  const starts = [...src.matchAll(/^ {6}id: (\d+),$/gm)];
  starts.forEach((m, i) => {
    const body = src.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : src.length);
    const keys = new Set([...body.matchAll(/"clip:([\w-]+)"/g)].map((k) => k[1]));
    const list = /^ {6}clips: \[([^\]]*)\]/m.exec(body);
    if (list) [...list[1].matchAll(/"([\w-]+)"/g)].forEach((k) => keys.add(k[1]));
    for (const key of keys) {
      const f = path.join(dir, "clips", m[1] + "-" + key + ".mp3");
      if (!fs.existsSync(f)) throw new Error(name + ": cue " + m[1] + " uses clip \"" + key + "\" but " + path.relative(path.join(dir, ".."), f) + " is missing");
      clipCount++;
    }
  });
}

const out = "/* Generated by tools/build-fx-index.js - do not edit by hand. */\n" +
  "window.MachineFX && window.MachineFX.packs(" + JSON.stringify(map) + ");\n";
fs.writeFileSync(path.join(dir, "index.js"), out);
console.log("fx/index.js: " + seen.size + " ids in " + files.length + " packs" + (clipCount ? ", " + clipCount + " clip references checked" : ""));
